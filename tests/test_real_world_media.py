def test_multi_format_image_support():
    """Verify image detection works across common real-world formats: JPG, PNG, WEBP."""
    classifier = ImageForensicClassifier()
    classifier.load()

    arr = np.random.randint(60, 200, (256, 256, 3), dtype=np.uint8)
    base_img = Image.fromarray(arr)

    # 1. JPEG
    jpg_buf = io.BytesIO()
