def test_ai_generated_image_detection_multiple_generators():
    """
    Verify detection of AI-generated images across diverse generators:
    ChatGPT, DALL-E 3, Midjourney, and Stable Diffusion.
    Strict requirement: Never classify as REAL.
    """
    classifier = ImageForensicClassifier()
    classifier.load()

    generators = [
        ("DALL-E 3", "dall-e 3, prompt: futuristic architectural eco-city, 8k render"),
        ("Midjourney v6", "cinematic photo, photorealistic, 85mm lens --v 6.0 --ar 16:9"),
        ("Stable Diffusion XL", "Steps: 35, Sampler: DPM++ 2M Karras, CFG scale: 7, Model: SDXL_v1.0"),
        ("ChatGPT / DALL-E", "generated by chatgpt, dall-e synthetic visual output")
    ]

    for gen_name, prompt_info in generators:
        # Create synthetic image with generative metadata
        arr = np.zeros((384, 384, 3), dtype=np.uint8)
        for y in range(384):
            for x in range(384):
                arr[y, x] = [int(x * 0.6), int(y * 0.6), int((x + y) * 0.3)]
        
        pil_img = Image.fromarray(arr)
        png_bytes = io.BytesIO()
        info = PngInfo()
        info.add_text("parameters", prompt_info)
        info.add_text("software", gen_name)
        pil_img.save(png_bytes, format="PNG", pnginfo=info)
        png_bytes.seek(0)

        res = classifier.predict_image(Image.open(png_bytes))
        assert res["prediction"] == "AI_GENERATED", f"{gen_name} image was not flagged as AI_GENERATED (got {res['prediction']})"
        assert res["prediction"] != "REAL", f"CRITICAL: {gen_name} image was classified as REAL!"
        assert res["confidence"] >= 0.50
        assert "generative" in res["explanation"].lower() or "ai" in res["explanation"].lower()

