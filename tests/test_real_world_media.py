def test_synthetic_ai_video_and_flicker_timestamps():
    """
    Verify video analysis on synthetic MP4 clip with sharp temporal splicing
    detects temporal flicker and outputs accurate suspicious timestamps.
    """
    classifier = VideoForensicClassifier(target_fps=2.0, max_frames=20)
    classifier.load()

    temp_vid = "test_spliced_temporal.mp4"
    fourcc = cv2.VideoWriter_fourcc(*'mp4v')
    out = cv2.VideoWriter(temp_vid, fourcc, 10.0, (160, 160))
    for i in range(25):
        if i in [7, 8, 17, 18]:
            # Spliced cut / discontinuous frames
            frame = np.random.randint(0, 255, (160, 160, 3), dtype=np.uint8)
        else:
            frame = np.full((160, 160, 3), (i * 8) % 255, dtype=np.uint8)
        out.write(frame)
    out.release()

    try:
        res = classifier.predict_video(temp_vid)
        assert res["prediction"] in ["FAKE_MANIPULATED", "DEEPFAKE", "AI_GENERATED", "SUSPICIOUS"]
        assert res["prediction"] != "REAL"
        assert res["temporal_flicker"] > 0.10
        assert len(res["suspicious_timestamps"]) > 0
        first_anomaly = res["suspicious_timestamps"][0]
        assert "timestamp" in first_anomaly
        assert "reasons" in first_anomaly
    finally:
        if os.path.exists(temp_vid):
            os.remove(temp_vid)

def test_full_benchmark_metrics_computation():
    """Run empirical evaluation across multi-category media and compute confusion matrix & F1 scores."""
    classifier = ImageForensicClassifier()
    classifier.load()

    au_dir = os.path.join(CASIA_DIR, "Au")
    tp_dir = os.path.join(CASIA_DIR, "Tp")
    if not os.path.exists(au_dir) or not os.path.exists(tp_dir):
        pytest.skip("CASIA dataset not available")

    y_true = []
    y_pred = []

    # 10 authentic camera images
    for p in [os.path.join(au_dir, f) for f in os.listdir(au_dir) if f.endswith(".jpg")][:10]:
        res = classifier.predict_image(p)
        y_true.append("real")
        y_pred.append("real" if res["prediction"] == "REAL" else "fake")

    # 10 tampered images
    for p in [os.path.join(tp_dir, f) for f in os.listdir(tp_dir) if f.endswith(".jpg")][:10]:
        res = classifier.predict_image(p)
        y_true.append("fake")
        y_pred.append("fake" if res["prediction"] in ["FAKE_TAMPERED", "AI_GENERATED", "DEEPFAKE", "SUSPICIOUS"] else "real")

    # 5 AI-generated images
    for i in range(5):
        arr = np.full((256, 256, 3), 120 + i * 10, dtype=np.uint8)
        pil_img = Image.fromarray(arr)
        buf = io.BytesIO()
        info = PngInfo()
        info.add_text("parameters", f"Midjourney v6 realistic render seed {i}")
        pil_img.save(buf, format="PNG", pnginfo=info)
        buf.seek(0)
        res = classifier.predict_image(Image.open(buf))
        y_true.append("fake")
        y_pred.append("fake" if res["prediction"] in ["AI_GENERATED", "FAKE_TAMPERED", "SUSPICIOUS"] else "real")

    acc = accuracy_score(y_true, y_pred)
    report = classification_report(y_true, y_pred, output_dict=True, zero_division=0)
    cm = confusion_matrix(y_true, y_pred, labels=["fake", "real"])

    print(f"\nEmpirical Real-World Evaluation: Accuracy={acc:.2%}, Macro F1={report['macro avg']['f1-score']:.4f}")
    print("Confusion Matrix (fake, real):", cm.tolist())
    assert acc >= 0.75, f"Accuracy below target threshold: {acc:.2%}"
