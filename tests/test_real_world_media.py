    png_buf.seek(0)
    res_png = classifier.predict_image(Image.open(png_buf))
    assert res_png["prediction"] in ["REAL", "SUSPICIOUS"]

    # 3. WEBP
    webp_buf = io.BytesIO()
    base_img.save(webp_buf, format="WEBP", quality=85)
    webp_buf.seek(0)
    res_webp = classifier.predict_image(Image.open(webp_buf))
    assert res_webp["prediction"] in ["REAL", "SUSPICIOUS"]

